declare(strict_types=1);

namespace Podquilt\Tools\ContextSystem;

use JsonException;
use RuntimeException;

final readonly class ContextSystem
{
    private const GENERATED_MARKDOWN_NOTICE = '<!-- Generated by composer context:build. Do not edit by hand. -->';
    private const GENERATED_MERMAID_NOTICE = '<!-- Generated by composer context:build. Do not edit by hand. -->';
    private const PHPSTAN_IGNORE_TOKEN = '@phpstan' . '-ignore';

    /**
     * @var list<string>
     */
    private const BACKLOG_MARKERS = [
        'TO' . 'DO',
        'FIX' . 'ME',
        'HA' . 'CK',
        'X' . 'XX',
    ];

    /**
     * @var list<string>
     */
    private const WALK_IGNORES = [
        '.agent-context',
        '.git',
        '.phpstan',
        '.phpunit.cache',
        'logs',
        'media',
        'spec/generated',
        'vendor',
    ];

    public function __construct(
        private string $repoRoot,
        private PhpDependencyScanner $dependencyScanner = new PhpDependencyScanner(),
    ) {
    }

    public function loadContextData(): ContextData
    {
        $glossary = $this->loadJsonFile('glossary/terms.json');
        $subsystemIndex = $this->loadJsonFile('spec/subsystems/index.json');
        $subsystems = [];

        foreach ($this->listFiles('spec/subsystems') as $relativePath) {
            if (!str_ends_with($relativePath, '.json') || $relativePath === 'spec/subsystems/index.json') {
                continue;
            }

            $record = $this->loadJsonFile($relativePath);
            $record['filePath'] = $relativePath;
            $subsystems[] = $record;
        }

        usort(
            $subsystems,
            static fn (array $left, array $right): int => $left['id'] <=> $right['id'],
        );

        $decisionPaths = array_values(
            array_filter(
                $this->listFiles('spec/decisions'),
                static fn (string $relativePath): bool => str_ends_with($relativePath, '.md'),
            ),
        );
        sort($decisionPaths);

        $this->validateGlossary($glossary);
        $this->validateSubsystemIndex($subsystemIndex);
        $this->validateSubsystems($subsystems);

        return new ContextData(
            repoRoot: $this->repoRoot,
            glossary: $glossary,
            subsystemIndex: $subsystemIndex,
            subsystems: $subsystems,
            decisionPaths: $decisionPaths,
        );
    }

    /**
     * @return array{flags: array<string, string>, positionals: list<string>}
     */
    public static function parseArgs(array $argv): array
    {
        $flags = [];
        $positionals = [];

        foreach ($argv as $argument) {
            if (!str_starts_with($argument, '--')) {
                $positionals[] = $argument;
                continue;
            }

            $raw = substr($argument, 2);
            $parts = explode('=', $raw, 2);
            $flags[$parts[0]] = $parts[1] ?? 'true';
        }

        return [
            'flags' => $flags,
            'positionals' => $positionals,
        ];
    }

    /**
     * @return list<string>
     */
    public function writeContextArtifacts(ContextData $contextData): array
    {
        $outputs = $this->buildContextArtifacts($contextData);
        $changedFiles = [];

        foreach ($outputs as $relativePath => $contents) {
            if ($this->writeTextIfChanged($relativePath, $contents)) {
                $changedFiles[] = $relativePath;
            }
        }

        sort($changedFiles);

        return $changedFiles;
    }

    /**
     * @return array<string, string>
     */
    public function buildContextArtifacts(ContextData $contextData): array
    {
        $repoMap = $this->buildRepoMap($contextData);
        $this->assertOwnedCoverage($repoMap);

        return [
            'glossary/README.md' => $this->generateGlossaryReadme($contextData->glossary),
            'spec/generated/repo-map.json' => $this->encodeJson([
                'generatedBy' => 'composer context:build',
                'version' => 1,
                'files' => $repoMap['files'],
                'subsystems' => $repoMap['subsystems'],
            ]),
            'spec/generated/subsystem-graph.mmd' => $this->renderSubsystemGraph($contextData),
        ];
    }

    /**
     * @param list<string> $allowLocked
     * @return array<string, mixed>
     */
    public function buildTaskPacket(ContextData $contextData, string $task, array $allowLocked = []): array
    {
        $normalizedTask = trim($task);

        if ($normalizedTask === '') {
            throw new RuntimeException('A non-empty task description is required.');
        }

        $tokens = $this->tokenize($normalizedTask);
        $scoredSubsystems = [];

        foreach ($contextData->subsystems as $subsystem) {
            $scoredSubsystems[] = $this->scoreSubsystem(
                $subsystem,
                $contextData->glossary,
                $normalizedTask,
                $tokens,
            );
        }

        usort(
            $scoredSubsystems,
            static fn (array $left, array $right): int => $right['score'] <=> $left['score'] ?: ($left['subsystem']['id'] <=> $right['subsystem']['id']),
        );

        [$selectedIds, $expandedIds] = $this->expandSubsystemSelection(
            $scoredSubsystems,
            $contextData->subsystems,
        );
        $selectedSubsystems = array_values(
            array_filter(
                $contextData->subsystems,
                static fn (array $subsystem): bool => in_array($subsystem['id'], $expandedIds, true),
            ),
        );
        $lockedSubsystems = array_values(
            array_map(
                static fn (array $subsystem): string => $subsystem['id'],
                array_filter(
                    $selectedSubsystems,
                    static fn (array $subsystem): bool => $subsystem['status'] === 'locked',
                ),
            ),
        );
        sort($lockedSubsystems);

        $filteredAllowLocked = array_values(
            array_filter(
                array_unique($allowLocked),
                static fn (string $subsystemId): bool => in_array($subsystemId, $lockedSubsystems, true),
            ),
        );
        sort($filteredAllowLocked);

        $requiredSpecReads = ['spec/README.md'];
        $requiredDocsReads = [];
        $requiredDecisionReads = [];
        $requiredTests = [];
        $glossaryTerms = [];
        $requiredSubsystemRecords = [];

        foreach ($selectedSubsystems as $subsystem) {
            foreach ($subsystem['required_reads']['spec'] as $entry) {
                $requiredSpecReads[] = $entry;
            }

            foreach ($subsystem['required_reads']['docs'] as $entry) {
                $requiredDocsReads[] = $entry;
            }

            foreach ($subsystem['required_reads']['decisions'] as $entry) {
                $requiredDecisionReads[] = $entry;
            }

            foreach ($subsystem['tests'] as $entry) {
                $requiredTests[] = $entry;
            }

            foreach ($subsystem['glossary_terms'] as $entry) {
                $glossaryTerms[] = $entry;
            }

            $requiredSubsystemRecords[] = $subsystem['filePath'];
        }

        $matchedSubsystems = array_values(
            array_map(
                static fn (array $entry): array => [
                    'id' => $entry['subsystem']['id'],
                    'reasons' => $entry['reasons'],
                    'score' => $entry['score'],
                    'status' => $entry['subsystem']['status'],
                ],
                array_filter(
                    $scoredSubsystems,
                    static fn (array $entry): bool => $entry['score'] > 0,
                ),
            ),
        );

        return [
            'task' => $normalizedTask,
            'createdAt' => date(DATE_ATOM),
            'confidence' => $this->determineTaskConfidence($scoredSubsystems, $selectedIds),
            'matchedSubsystems' => $matchedSubsystems,
            'selectedSubsystemIds' => $selectedIds,
            'touchedSubsystemIds' => array_values(array_map(static fn (array $subsystem): string => $subsystem['id'], $selectedSubsystems)),
            'lockedSubsystems' => $lockedSubsystems,
            'allowLocked' => $filteredAllowLocked,
            'requiredSpecReads' => $this->uniqueSorted($requiredSpecReads),
            'requiredDocsReads' => $this->uniqueSorted($requiredDocsReads),
            'requiredDecisionReads' => $this->uniqueSorted($requiredDecisionReads),
            'requiredTests' => $this->uniqueSorted($requiredTests),
            'requiredSubsystemRecords' => $this->uniqueSorted($requiredSubsystemRecords),
            'glossaryTerms' => $this->uniqueSorted($glossaryTerms),
        ];
    }

    /**
     * @param array<string, mixed> $taskPacket
     */
    public function writeActiveTask(ContextData $contextData, array $taskPacket): void
    {
        $this->writeTextIfChanged(
            (string) $contextData->subsystemIndex['task_state_path'],
            $this->encodeJson($taskPacket),
        );
        $this->writeTextIfChanged(
            (string) $contextData->subsystemIndex['task_markdown_path'],
            $this->renderTaskMarkdown($taskPacket),
        );
    }

    /**
     * @return array{markdown: string, changedFiles: list<string>, touchedSubsystems: list<array<string, mixed>>}
     */
    public function buildReviewPacket(ContextData $contextData): array
    {
        $activeTask = $this->readActiveTask((string) $contextData->subsystemIndex['task_state_path']);

        if ($activeTask === null) {
            throw new RuntimeException('Cannot build a review packet without .agent-context/active-task.json. Run composer context:task first.');
        }

        $changedFiles = array_values(
            array_filter(
                $this->getGitStatus(),
                static fn (string $relativePath): bool => !str_starts_with($relativePath, '.agent-context/'),
            ),
        );
        $touchedSubsystemIds = $this->touchedSubsystemIdsForFiles($contextData, $changedFiles);
        $touchedSubsystems = array_values(
            array_filter(
                $contextData->subsystems,
                static fn (array $subsystem): bool => in_array($subsystem['id'], $touchedSubsystemIds, true),
            ),
        );
        $changedAuthoritativeArtifacts = array_values(
            array_filter(
                $changedFiles,
                static fn (string $relativePath): bool => str_starts_with($relativePath, 'spec/')
                    || str_starts_with($relativePath, 'docs/')
                    || str_starts_with($relativePath, 'glossary/')
                    || in_array($relativePath, ['README.md', 'AGENTS.md'], true),
            ),
        );

        $lines = [
            '# Drift Review Packet',
            '',
            'Task: ' . $activeTask['task'],
            'Confidence: ' . $activeTask['confidence'],
            '',
            '## Changed Files',
            '',
        ];

        foreach ($changedFiles as $entry) {
            $lines[] = '- ' . $entry;
        }

        $lines[] = '';
        $lines[] = '## Touched Subsystems';
        $lines[] = '';

        foreach ($touchedSubsystems as $subsystem) {
            $lines[] = '- ' . $subsystem['id'] . ' (' . $subsystem['status'] . ')';

            foreach ($subsystem['invariants'] as $invariant) {
                $lines[] = '  - ' . $invariant['id'] . ': ' . $invariant['statement'];
            }
        }

        $lines[] = '';
        $lines[] = '## Changed Authoritative Artifacts';
        $lines[] = '';

        foreach ($changedAuthoritativeArtifacts as $entry) {
            $lines[] = '- ' . $entry;
        }

        $lines[] = '';

        return [
            'markdown' => implode("\n", $lines),
            'changedFiles' => $changedFiles,
            'touchedSubsystems' => $touchedSubsystems,
        ];
    }

    public function writeReviewPacket(ContextData $contextData, string $markdown): void
    {
        $this->writeTextIfChanged(
            (string) $contextData->subsystemIndex['review_packet_path'],
            $markdown,
        );
    }

    public function checkContextState(ContextData $contextData): void
    {
        $staleArtifacts = $this->diffGeneratedArtifacts($contextData);

        if ($staleArtifacts !== []) {
            throw new RuntimeException(
                "Derived context artifacts are stale. Run composer context:build.\n" . $this->formatList($staleArtifacts),
            );
        }

        $changedFiles = array_values(
            array_filter(
                $this->getGitStatus(),
                fn (string $relativePath): bool => !$this->isLocalOutput($contextData, $relativePath)
                    && !$this->isDerivedArtifact($contextData, $relativePath),
            ),
        );

        if ($changedFiles === []) {
            return;
        }

        $activeTask = $this->readActiveTask((string) $contextData->subsystemIndex['task_state_path']);

        if ($activeTask === null) {
            throw new RuntimeException('Changed files detected without .agent-context/active-task.json. Run composer context:task -- "<task>" first.');
        }

        $this->checkTaskCoverage($contextData, $activeTask, $changedFiles);
    }

    public function checkTerminology(ContextData $contextData): void
    {
        $findings = [];

        foreach ($this->collectFirstPartyFiles($contextData) as $relativePath) {
            if (!$this->isTextCheckFile($relativePath) || $relativePath === 'glossary/terms.json' || $this->isDerivedArtifact($contextData, $relativePath)) {
                continue;
            }

            $contents = $this->readText($relativePath);
            $loweredContents = strtolower($contents);

            foreach ($contextData->glossary['terms'] as $term) {
                foreach ($term['discouraged'] as $discouragedValue) {
                    if (str_contains($loweredContents, strtolower((string) $discouragedValue))) {
                        $findings[] = sprintf(
                            '%s: discouraged term "%s" should be replaced with "%s".',
                            $relativePath,
                            $discouragedValue,
                            $term['canonical'],
                        );
                    }
                }
            }
        }

        if ($findings !== []) {
            throw new RuntimeException(implode("\n", $findings));
        }
    }

    public function checkComments(ContextData $contextData): void
    {
        $findings = [];

        foreach ($this->collectFirstPartyFiles($contextData) as $relativePath) {
            if (!$this->isTextCheckFile($relativePath) || $this->isDerivedArtifact($contextData, $relativePath)) {
                continue;
            }

            $contents = $this->readText($relativePath);
            $lines = explode("\n", $contents);
            $isMarkdown = str_ends_with($relativePath, '.md');
            $insideFence = false;

            foreach ($lines as $index => $line) {
                $lineForChecks = $this->lineForCommentChecks($line, $isMarkdown, $insideFence);

                if ($lineForChecks === null) {
                    continue;
                }

                if ($this->containsBacklogMarker($lineForChecks)) {
                    $findings[] = sprintf(
                        '%s:%d contains a backlog-style comment.',
                        $relativePath,
                        $index + 1,
                    );
                }

                if (
                    str_contains($lineForChecks, self::PHPSTAN_IGNORE_TOKEN)
                    && !preg_match(
                        '/' . preg_quote(self::PHPSTAN_IGNORE_TOKEN, '/') . '(?:-[a-z-]+)?\s+--\s+\S/',
                        $lineForChecks,
                    )
                ) {
                    $findings[] = sprintf(
                        '%s:%d contains an %s directive without a reason introduced by "--".',
                        $relativePath,
                        $index + 1,
                        self::PHPSTAN_IGNORE_TOKEN,
                    );
                }
            }
        }

        if ($findings !== []) {
            throw new RuntimeException(implode("\n", $findings));
        }
    }

    public function checkArchitecture(ContextData $contextData): void
    {
        $repoMap = $this->buildRepoMap($contextData);
        $findings = [];

        foreach ($contextData->subsystemIndex['architecture_rules'] as $rule) {
            foreach ($repoMap['files'] as $file) {
                if ($file['type'] !== 'code' || !PathMatcher::anyMatches($file['path'], $rule['from'])) {
                    continue;
                }

                foreach ($file['imports'] as $importPath) {
                    $isForbidden = PathMatcher::anyMatches($importPath, $rule['forbidden']);
                    $isAllowed = PathMatcher::anyMatches($importPath, $rule['allowed'] ?? []);
                    $isExcepted = false;

                    foreach ($rule['exceptions'] ?? [] as $exception) {
                        if (
                            PathMatcher::matches($file['path'], $exception['from'])
                            && PathMatcher::matches($importPath, $exception['to'])
                        ) {
                            $isExcepted = true;
                            break;
                        }
                    }

                    if ($isForbidden && !$isAllowed && !$isExcepted) {
                        $findings[] = sprintf(
                            "%s: %s -> %s\n  %s",
                            $rule['id'],
                            $file['path'],
                            $importPath,
                            $rule['message'],
                        );
                    }
                }
            }
        }

        if ($findings !== []) {
            throw new RuntimeException(implode("\n", $findings));
        }
    }

    public function formatBuildSummary(array $changedFiles): string
    {
        if ($changedFiles === []) {
            return 'Context artifacts already up to date.';
        }

        return "Updated context artifacts:\n" . $this->formatList($changedFiles);
    }

